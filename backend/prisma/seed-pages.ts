export async function seedPages() {
  for (const page of PAGES) {
    await prisma.page.upsert({
      where: { slug: page.slug },
      update: {},  // не перезаписываем если уже есть (редакторские правки)
      create: page,
    });
    console.log(`Страница /${page.slug} готова`);
  }
}

seedPages()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
